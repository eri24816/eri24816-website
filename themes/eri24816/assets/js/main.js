// a trick to force clear thumbnail

document.addEventListener('DOMContentLoaded', () => {
    const iframes = []
    document.querySelectorAll('iframe').forEach(item => {
        if (item.clientWidth < 321) {
            item.width = 321;
            item.height = item.clientHeight * (321 / item.clientWidth);
            item.style.transform = `scale(${item.clientWidth / 321})`;
        }
    })

});